package de.lubowiecki.libs;

public class Config {

    private String user;
    private String password;
    private String host;
    private String port;
    private String driver;

    public String getUser() {
        return user;
    }

    public String getPassword() {
        return password;
    }

    public String getHost() {
        return host;
    }

    public String getPort() {
        return port;
    }

    public String getDriver() {
        return driver;
    }
}
